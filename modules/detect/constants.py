@dataclass
class SchedulingConfig:
    """检定排程算法默认参数（8.16 版）。

    8.16 起 spec_time 以 VW_DETECT_EQUIP_TYPE 码为键（低压电流互感器子类型
    大变比/DBI 默认时长均 25 分钟），default_times 由中文名键改为 int 码键。
    """
    default_times: Dict[int, int] = field(default_factory=lambda: {
        2: 414,   # 三相电能表（三相直接表）
        3: 414,   # 三相互感表
        1: 108,   # 单相电能表
        14: 414,  # 智能量测终端
        4: 25,    # 10kV电压互感器
        5: 30,    # 20kV电压互感器
        6: 25,    # 10kV电流互感器
        7: 30,    # 20kV电流互感器
        8: 25,    # 低压电流互感器
        9: 25,    # 低压电流互感器_大变比
        10: 25,   # 低压电流互感器_DBI
    })
    default_gap_minutes: float = 5.0          # 调度时间间隔（分钟）
    default_base_date: datetime = datetime(2026, 3, 1, 9, 0, 0)
    default_work_start: Tuple[int, int] = (9, 0)    # 默认上班时间
    default_work_end: Tuple[int, int] = (17, 0)     # 默认下班时间
    max_day_search: int = 365 * 10                  # 最大搜索天数，防止死循环


